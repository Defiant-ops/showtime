CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    password VARCHAR2(200) NOT NULL,
    role VARCHAR2(30) DEFAULT 'USER' NOT NULL
);

CREATE TABLE events (
    event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    description CLOB,
    category VARCHAR2(80) NOT NULL,
    venue VARCHAR2(200) NOT NULL,
    event_date TIMESTAMP NOT NULL,
    capacity NUMBER NOT NULL,
    price NUMBER(10,2) DEFAULT 0 NOT NULL,
    status VARCHAR2(30) DEFAULT 'OPEN' NOT NULL
);

CREATE TABLE bookings (
    booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    event_id NUMBER NOT NULL,
    booking_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    status VARCHAR2(30) DEFAULT 'CONFIRMED' NOT NULL,
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_booking_event FOREIGN KEY (event_id) REFERENCES events(event_id)
);

CREATE TABLE payments (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id NUMBER NOT NULL UNIQUE,
    amount NUMBER(10,2) NOT NULL,
    payment_method VARCHAR2(40) NOT NULL,
    payment_status VARCHAR2(30) DEFAULT 'PAID' NOT NULL,
    transaction_ref VARCHAR2(100) NOT NULL,
    CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id)
);


CREATE TABLE  ticket{
    ticket_ID INTEGER(12) UNIQUE PRIMARY KEY,
    Ticket_type VARCHAR(20),
    status VARCHAR(20),
    price NUMBER(10,2),
    booking_id NUMBER NOT NULL,
    CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id)
}

CREATE TABLE ticket_type{
    ticket_ID INTEGER(12) UNIQUE PRIMARY KEY,
    Ticket_type VARCHAR(20),
    lounge_access VARCHAR(3),
    comp_food varchar(3),
    seat VARCHAR(20),
    CONSTRAINT fk_tix_id FOREIGN KEY (ticket_ID) REFERENCES ticket(ticket_ID),
    CONSTRAINT fk_tix_type FOREIGN KEY (Ticket_type) REFERENCES ticket(ticket_type)
}