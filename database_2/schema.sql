CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(200) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'USER'
);

CREATE TABLE events (
    event_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description STRING NOT NULL,
    category VARCHAR(80) NOT NULL,
    venue VARCHAR(200) NOT NULL,
    event_date TIMESTAMPTZ NOT NULL,
    capacity INT NOT NULL,
    price DECIMAL(10, 2) NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN'
);

CREATE TABLE bookings (
    booking_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    event_id INT NOT NULL,
    booking_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    status VARCHAR(30) NOT NULL DEFAULT 'CONFIRMED',
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_booking_event FOREIGN KEY (event_id) REFERENCES events(event_id)
);

CREATE TABLE payments (
    payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INT NOT NULL UNIQUE,
    amount DECIMAL(10, 2) NOT NULL,
    payment_method VARCHAR(40) NOT NULL,
    payment_status VARCHAR(30) NOT NULL DEFAULT 'PAID',
    transaction_ref VARCHAR(100) NOT NULL,
    CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id)
);

CREATE TABLE ticket_type (
    ticket_type_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR(40) NOT NULL UNIQUE,
    lounge_access CHAR(1) NOT NULL DEFAULT 'N',
    complimentary_food CHAR(1) NOT NULL DEFAULT 'N',
    CONSTRAINT ck_ticket_lounge CHECK (lounge_access IN ('Y', 'N')),
    CONSTRAINT ck_ticket_food CHECK (complimentary_food IN ('Y', 'N'))
);

CREATE TABLE ticket (
    ticket_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INT NOT NULL UNIQUE,
    ticket_type_id INT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    price DECIMAL(10, 2) NOT NULL,
    seat VARCHAR(20),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_ticket_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id),
    CONSTRAINT fk_ticket_type FOREIGN KEY (ticket_type_id) REFERENCES ticket_type(ticket_type_id)
);

CREATE INDEX idx_bookings_user_event ON bookings (user_id, event_id);
CREATE INDEX idx_bookings_event_date ON bookings (booking_date);
CREATE INDEX idx_payments_booking_id ON payments (booking_id);
CREATE INDEX idx_ticket_booking_id ON ticket (booking_id);
CREATE INDEX idx_ticket_type_name ON ticket_type (type_name);
